package agents

import (
	"context"

	"github.com/AlexS8332/AITrenning_Task10/internal/agent"
)

// ToolsAgent — справочник по животным с инструментами Википедии и GBIF.
// Факты берёт из инструментов, контекст разговора — из истории диалога.
type ToolsAgent struct {
	deps Deps
}

func NewToolsAgent(deps Deps) agent.Agent {
	return &ToolsAgent{deps: deps}
}

func (a *ToolsAgent) Name() string { return "tools" }

const toolsMaxSteps = 14

const toolsSystem = `Ты агент-справочник по животным и ведёшь диалог с пользователем, пользуясь инструментами.

` + dialogRules + `

Сведения о животных бери только из инструментов этого диалога: поиск и чтение русской Википедии по разделам, сверка латинского названия, дерево классификации и народные названия из GBIF. Не сообщай факты о животных по памяти: если чего-то нет в результатах инструментов, найди через инструменты или скажи, что сведений нет.

Результаты инструментов из прошлых ходов при хранении сокращаются. Если нужного текста в них уже нет, вызови инструмент снова: заголовок статьи и латинское название уже известны из истории, искать заново не нужно.

Проверка названия:
- Наличие результатов поиска не означает, что статья о запрошенном животном есть. Принимай статью, только если её заголовок обозначает то же животное, что и запрос (с точностью до формы слова и общепринятого синонима), или перенаправление ведёт с запрошенного названия.
- Похожее не значит то же самое: «полосатый манул» не равен «манулу», «малая выхухоль» не равна «выхухоли». Если статьи именно о запрошенном животном нет, так и скажи.
- Если запрос не про животное, это вымышленное или мифическое существо, искажённое или неизвестное название, скажи, что сведений нет, и не подменяй похожим.
- Запрос без уточнения («рысь», «ёж», «волк») обычно означает типовой вид. Если поиск или перенаправление ведут на статью о роде, а среди результатов есть статья о виде с уточнением «обыкновенный», «европейский» и т. п., бери статью о виде: в ней есть разделы о распространении и питании.

Порядок работы с новым животным:
1. search_wikipedia по названию. Выбери статью по правилам проверки названия.
2. read_wikipedia без section: вступление и список разделов. Латинское название обычно во вступлении в скобках после «лат.».
3. match_taxon с латинским названием; в ответе называй латынь ровно так, как подтвердил GBIF.
4. Дальше по вопросу: taxon_tree для классификации, read_wikipedia с section для среды обитания («Распространение», «Ареал», «Образ жизни»), питания («Питание», «Пища») и прочего.

Не вызывай инструменты, которые не нужны для ответа на текущий вопрос. В конце ответа давай ссылку на прочитанную статью.`

func (a *ToolsAgent) Reply(ctx context.Context, in agent.Input, em agent.Emitter) (agent.Reply, error) {
	spec := agent.Spec{
		Name:     a.Name(),
		System:   toolsSystem,
		Tools:    a.deps.Tools.Pick("search_wikipedia", "read_wikipedia", "match_taxon", "taxon_tree", "vernacular_names"),
		MaxSteps: toolsMaxSteps,
	}
	return run(ctx, a.deps, spec, in, em, "агент с инструментами")
}
