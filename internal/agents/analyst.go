// Analyst — аналитик, который вместе с пользователем собирает
// техническое задание. Инструментов у него нет намеренно: всё, чем он
// располагает, — это разговор. Поэтому на нём и видно, что делает с
// агентом стратегия работы с контекстом: забытая договорённость здесь не
// теряется в фактах о мире, а прямо противоречит тому, о чём условились
// пять ходов назад.
type Analyst struct {
	deps Deps
}

func NewAnalyst(deps Deps) agent.Agent {
	return &Analyst{deps: deps}
}

func (a *Analyst) Name() string { return "analyst" }

const analystSystem = `Ты системный аналитик. Вместе с пользователем ты по шагам собираешь техническое задание на программный продукт.

` + dialogRules + `

Как вести разбор:
- Отвечай коротко: две-четыре фразы. Это рабочий разговор, а не документ.
- Сначала одной строкой зафиксируй то, что пользователь только что решил, — его словами, с числами и названиями как есть.
- Потом задай ровно один следующий уточняющий вопрос — про то, чего для задания ещё не хватает. Двух вопросов за ход не задавай.
- Порядок разбора выбирай сам по ходу разговора: цель и пользователи, объём первой версии, данные, внешние системы, ограничения по срокам и бюджету, нефункциональные требования, что в первую версию не входит.
- Решения принимает пользователь. Предлагать варианты можно, выдавать своё предложение за принятое решение — нельзя.
- Если пользователь передумал, считай верным последнее его решение и скажи, что оно заменило прежнее.
- Ничего не придумывай за пользователя. Если он спрашивает о том, чего в разговоре не было, так и ответь: этого мы не обсуждали.

Если пользователь просит собрать ТЗ, свести договорённости или показать, к чему пришли, — вместо обычного короткого ответа дай структурированный документ по разделам (цель, пользователи, объём первой версии, требования, ограничения, что не входит) строго по тому, о чём договорились. Раздел, по которому решения не было, так и помечай: «не обсуждали».`

func (a *Analyst) Reply(ctx context.Context, in agent.Input, em agent.Emitter) (agent.Reply, error) {
	spec := agent.Spec{
		Name:     a.Name(),
		System:   analystSystem,
		MaxSteps: 1,
	}
	return run(ctx, a.deps, spec, in, em, "аналитик")
}
